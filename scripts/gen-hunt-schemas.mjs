#!/usr/bin/env node
// Generate the JSON Schemas the hunt-* skills and agents are told to produce (ADR-0054 §4).
//
// The zod contracts in packages/marvin-mcp-shared/src/contracts/hunt.ts are the one source of
// truth: the `hunt` tool validates with them at runtime, and these files are the same shapes in
// a form a prompt can point an agent at. Committed, so an agent can read them without a build;
// `--check` fails when a committed file no longer matches the contract, and
// test/hunt-schemas.test.mjs runs that check.
//
// Reads the BUILT shared library (`npm run build -w @marvin-toolkit/mcp-shared` first).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { zodToJsonSchema } from "zod-to-json-schema";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "plugins", "marvin", "skills", "hunt-code", "references", "schemas");
const contracts = await import(
  pathToFileURL(join(root, "packages", "marvin-mcp-shared", "dist", "contracts", "index.js")).href
);

const SCHEMAS = {
  "finding.schema.json": [
    "FindingClaim",
    'One finding claim, as `hunt action: "record"` takes it.',
  ],
  "flows.schema.json": ["FlowMap", 'The flow map, as `hunt action: "flows"` takes it.'],
  "verdict.schema.json": [
    "VerdictEntry",
    'One ruling, as `hunt action: "verdict"` takes it (`at` is filled by the tool).',
  ],
  "config.schema.json": ["HuntConfig", "The `hunt` key of .marvin/config.json."],
};

export function render(name) {
  const [exportName, description] = SCHEMAS[name];
  const schema = zodToJsonSchema(contracts[exportName], {
    name: exportName,
    $refStrategy: "none",
    target: "jsonSchema7",
  });
  const body = {
    $comment:
      "Generated by scripts/gen-hunt-schemas.mjs from contracts/hunt.ts. Do not edit by hand.",
    description,
    ...schema,
  };
  return `${JSON.stringify(body, null, 2)}\n`;
}

const check = process.argv.includes("--check");
const stale = [];
mkdirSync(outDir, { recursive: true });
for (const name of Object.keys(SCHEMAS)) {
  const path = join(outDir, name);
  const next = render(name);
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    // absent: written below, or reported as stale under --check
  }
  if (current === next) continue;
  if (check) stale.push(name);
  else writeFileSync(path, next);
}
if (stale.length > 0) {
  console.error(
    `hunt schemas out of date: ${stale.join(", ")}. Run \`npm run gen:hunt-schemas\` and commit the result.`,
  );
  process.exit(1);
}
if (!check) console.log(`hunt schemas written to ${outDir}`);
